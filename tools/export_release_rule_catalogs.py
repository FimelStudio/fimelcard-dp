def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output/'22-璀璨宝石卡牌图鉴.md').write_text(splendor(), encoding='utf-8')
    (args.output/'23-胡闹运动会角色图鉴.md').write_text(magical_athlete(), encoding='utf-8')
    print('已导出璀璨宝石100张卡牌条目和胡闹运动会36名角色图鉴。')


if __name__ == '__main__':
    main()
