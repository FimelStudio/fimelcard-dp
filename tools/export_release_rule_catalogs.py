"""从游戏数据源导出发布版新手图鉴；不读取玩家世界。"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COLORS = ('钻石', '蓝宝石', '祖母绿', '红宝石', '缟玛瑙')


def cost_text(cost: list[int]) -> str:
    parts = [f'{name}{count}' for name, count in zip(COLORS, cost) if count]
    return '免费' if not parts else '＋'.join(parts)


def splendor() -> str:
    data = json.loads((ROOT/'tools/splendor_cards.json').read_text(encoding='utf-8'))
    out = ['# 璀璨宝石完整卡牌图鉴', '',
           '本表与 Fimel Cards v1.1 的实际牌库一致。发展卡费用按“钻石、蓝宝石、祖母绿、红宝石、缟玛瑙”记录；黄金不印在费用上，只在支付时充当任意颜色。', '',
           '> 📷 **截图位：发展卡牌面标注图**  ',
           '> 请用箭头标出左上角分数、右上角永久折扣颜色、下方五色费用，保存为 `images/screenshots/22-璀璨宝石-牌面图解.webp`。', '',
           '## 怎样读一张发展卡', '',
           '- **分数**：购买后立即加入声望。没有数字就是 0 分。',
           '- **永久折扣**：右上角宝石颜色。以后每次买牌都少付该颜色 1 颗，永不消耗。',
           '- **费用**：牌底各宝石下的数字。先减永久折扣，再用普通筹码支付，最后才用黄金补缺。',
           '- **等级**：一级便宜、主要建立折扣；二级兼顾折扣与分数；三级昂贵、分数最高。等级不是购买门槛，买得起即可购买。',
           '- 同等级、同奖励、同分数、同费用的卡在物品栏中会叠放；表中的每一行仍代表牌库里独立的一张牌。', '']
    for tier in (1, 2, 3):
        cards = [card for card in data['cards'] if card['tier'] == tier]
        out += [f'## {"一二三"[tier-1]}级发展卡（{len(cards)} 张）', '',
                '| 牌库编号 | 永久折扣 | 分数 | 印刷费用 |', '| ---: | --- | ---: | --- |']
        for card in cards:
            out.append(f"| {card['id']+1} | {COLORS[card['bonus']]} | {card['points']} | {cost_text(card['cost'])} |")
        out.append('')
    out += ['## 贵族卡（10 张）', '',
            '贵族左下角显示的是所需**发展卡永久折扣**，不是手中的宝石筹码。达到要求后不支付卡牌，也不消耗折扣；贵族自动来访并提供 3 分。', '',
            '| 贵族编号 | 分数 | 来访要求 |', '| ---: | ---: | --- |']
    for noble in data['nobles']:
        out.append(f"| {noble['id']+1} | {noble['points']} | {cost_text(noble['cost'])} |")
    out += ['', '## 新手看牌顺序', '',
            '1. 先看自己缺哪种永久折扣，不要只盯着当前分数。',
            '2. 再看这张卡减去折扣后的实际费用；桌上出现“免费”时可直接购买。',
            '3. 检查贵族需求。如果只差一张发展卡，通常比多拿一轮筹码更重要。',
            '4. 买不起但担心被别人拿走时，可以预定；预定上限为三张。', '',
            '---', '', '[返回璀璨宝石说明书](22-璀璨宝石.md) · [返回游戏规则目录](README.md)', '']
    return '\n'.join(out)


