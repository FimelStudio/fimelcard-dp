import fs from 'node:fs';
import assert from 'node:assert/strict';
const root='tools/doudizhu-play-hud/';
const read=n=>fs.readFileSync(root+n+'.mcfunction','utf8');
const play=read('action/play'),pass=read('action/pass');
assert(play.indexOf('function doudizhu:hud/record_play')>play.indexOf('execute unless score #beats dd_ctx matches 1 run return 0'));
assert(play.indexOf('function doudizhu:hud/record_play')<play.indexOf('dd_owner -1'));
assert(pass.indexOf('function doudizhu:hud/record_pass')>pass.indexOf('dd_type matches 0 run return 0'));
assert(read('hud/record_play').includes('dd_type matches 0 run data remove entity'));
assert(!read('hud/record_pass').includes('data remove'));
assert(read('hud/store_play').includes('data.doudizhu.hud_plays.s$(seat)'));
assert(read('hud/read_play').includes('data.doudizhu.hud_plays.s$(seat)'));
assert(read('hud/read_play').startsWith('data modify storage doudizhu:hud shown_play set value'));
const cards=[...read('hud/build_play').matchAll(/dd_card=(\d+),dd_selected=1/g)].map(m=>+m[1]);
assert.equal(cards.length,54);
assert.equal(new Set(cards).size,54);
assert(read('hud/row').includes('function doudizhu:hud/read_play with storage doudizhu:hud'));
assert(read('hud/row').includes('dy set value -12.0d'));
assert(read('hud/build').includes('y set value -52.0d'));
console.log('出牌/不出记录时机、牌桌座位隔离、空记录回退、54张牌及布局静态检查通过。');
